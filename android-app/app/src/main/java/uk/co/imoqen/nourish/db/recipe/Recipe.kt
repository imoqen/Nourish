package uk.co.imoqen.nourish.db.recipe

import androidx.room.ColumnInfo
import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.PrimaryKey
import androidx.room.Relation
import uk.co.imoqen.nourish.db.user.User

@Entity(tableName = "Recipe")
data class Recipe(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    @ColumnInfo(name = "ownerUid") val authorUid: Int,
    @ColumnInfo(name = "title") val title: Int,
    @ColumnInfo(name = "instructions") val instructions: String,
    @ColumnInfo(name = "numberOfServings") val numberOfServings: Int,
    @ColumnInfo(name = "colour") val colour: String, // store as hex
    @ColumnInfo(name = "generated") val generated: Boolean, // distinguishes between user inputted and generated by llm
    @ColumnInfo(name = "imagePath") val image: String?, // optional. only one image per recipe, so fine.
    @ColumnInfo(name = "archived") val archived: Boolean,
    @ColumnInfo(name = "recipeTypeId") val recipeTypeId: Int
)

data class RecipeWithIngredients(
    @Embedded val recipe: Recipe, // parent has field id
    @Relation(
        parentColumn = "id",
        entityColumn = "recipeId"
    )
    val ingredients: List<RecipeIngredient>, // entity has field recipeId
)

data class UserWithRecipes(
    @Embedded val user: User, // parent has field uid
    @Relation(
        parentColumn = "uid",
        entityColumn = "ownerUid"
    )
    val recipes: List<Recipe>, // entity has field ownerUid
)