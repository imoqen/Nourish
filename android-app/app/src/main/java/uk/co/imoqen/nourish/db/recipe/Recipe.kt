package uk.co.imoqen.nourish.db.recipe

import androidx.room.ColumnInfo
import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import androidx.room.Relation
import uk.co.imoqen.nourish.db.recipe.recipetype.RecipeType
import uk.co.imoqen.nourish.db.user.User

@Entity(
    tableName = "Recipe",
    foreignKeys = [
        // user relation:
        ForeignKey(
            entity = User::class,
            parentColumns = ["uid"], // the primary key of User
            childColumns = ["ownerUid"], // the foreign key which holds this reference, in Recipe
            onDelete = ForeignKey.CASCADE
        ),
        ForeignKey(
            entity = RecipeType::class,
            parentColumns = ["id"], // the primary key of RecipeType
            childColumns = ["recipeTypeId"], // the foreign key which holds this reference, in Recipe
            onDelete = ForeignKey.CASCADE
        ),
    ],
    indices = [
        Index("ownerUid"),
        Index("recipeTypeId"),
    ]
)
data class Recipe(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    @ColumnInfo(name = "ownerUid") val authorUid: String,
    @ColumnInfo(name = "title") val title: String,
    @ColumnInfo(name = "method") val method: String,
    @ColumnInfo(name = "numberOfServings") val numberOfServings: Int,
    @ColumnInfo(name = "colour") val colour: String, // store as hex
    @ColumnInfo(name = "generated") val generated: Boolean, // distinguishes between user inputted and generated by llm
    @ColumnInfo(name = "imagePath") val image: String?, // optional. only one image per recipe, so fine.
    @ColumnInfo(name = "archived") val archived: Boolean,
    @ColumnInfo(name = "storageInstructions") val storageInstructions: String,
    @ColumnInfo(name = "recipeTypeId") val recipeTypeId: Long
)

data class UserWithRecipes(
    @Embedded val user: User, // parent has field uid
    @Relation(
        parentColumn = "uid",
        entityColumn = "ownerUid"
    )
    val recipes: List<Recipe>, // entity has field ownerUid
)

// all recipes of a recipe type
data class RecipeTypeWithRecipes(
    @Embedded val recipeType: RecipeType, // parent
    @Relation(
        parentColumn = "id",
        entityColumn = "recipeTypeId"
    )
    val recipesOfType: List<Recipe>, // entity
)